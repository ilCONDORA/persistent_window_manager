// persistent_window_manager — native runner setup
// =================================================
//
// What it does
// ------------
// Patches the native desktop runner of the current Flutter project (Windows,
// Linux, macOS) so the window is NEVER shown by the OS or the Flutter engine
// on its own. From that point on, the only thing that decides when the window
// becomes visible is the explicit call to `windowManager.show()` made
// internally by `runAppPersistentWindowManager`.
//
// Why it's needed
// ---------------
// window_manager controls window visibility only through its own channel calls
// (`show()` / `hide()`). It has no control over the fact that the runner
// generated by `flutter create` shows the window on its own as soon as it is
// ready — which the default template does, differently on each platform. If
// this step is not applied, the window briefly appears with default geometry
// and only afterwards is moved/resized/maximized according to the saved state:
// exactly the flicker this package is designed to eliminate.
//
// Usage
// -----
// Run this command ONCE from the root of your Flutter app (the one that
// depends on persistent_window_manager), not from inside the package itself:
//
//   dart run persistent_window_manager:setup
//
// Add `--dry-run` (or `-n`) to preview what would be changed without
// writing anything to disk:
//
//   dart run persistent_window_manager:setup --dry-run
//
// Safety and idempotency
// ----------------------
// - Each file is touched only if it exists and only if the expected pattern
//   is found EXACTLY once. In case of ambiguity or unrecognised pattern, the
//   file is left untouched and reported as "needs manual fix", with a
//   reference to the "Manual setup" section of the README.
// - Re-running the command is safe: every patch leaves a recognisable marker
//   (see `_marker`) and is skipped if already present.
// - Your project is almost certainly under git: review `git diff` after
//   running before committing.
//
// Known limitations
// -----------------
// - Files are processed as text with `\n` line endings. If a file uses CRLF
//   (`\r\n`), pattern detection still works (comparisons use `trim()`, which
//   also strips `\r`), but lines inserted by this script will use `\n`,
//   resulting in mixed line endings in the file — harmless for compilation,
//   but noted here for transparency.
// - The Linux template (`my_application.cc`) has changed across Flutter
//   versions: this script recognises both the legacy variant (immediate show
//   after window creation) and the modern variant (show hooked to the FlView
//   "first-frame" signal). If your project uses a further customised template,
//   it will be reported as "unrecognised pattern" rather than risk an
//   incorrect modification.

import 'dart:io';

/// Marker inserted in every patched file to make the operation idempotent and recognisable in a `git diff`.
const String _marker = 'persistent_window_manager:setup';

enum _Status { patched, alreadyOk, platformNotFound, unrecognized, error }

class _PatchResult {
  const _PatchResult(this.platform, this.path, this.status, this.message);

  final String platform;
  final String path;
  final _Status status;
  final String message;
}

void main(List<String> args) {
  final bool dryRun = args.contains('--dry-run') || args.contains('-n');
  final Directory projectRoot = Directory.current;

  if (!File('${projectRoot.path}/pubspec.yaml').existsSync()) {
    stderr.writeln(
      'No pubspec.yaml found in "${projectRoot.path}".\n'
      'Run this command from the root of your Flutter app (the one that\n'
      'depends on persistent_window_manager), not from inside the package\n'
      'itself:\n'
      '\n'
      '  dart run persistent_window_manager:setup\n',
    );
    exitCode = 2;
    return;
  }

  final List<_PatchResult Function(Directory, bool)> patchers = <_PatchResult Function(Directory, bool)>[
    _patchWin32Window,
    _patchFlutterWindow,
    _patchLinuxMyApplication,
    _patchMacosMainFlutterWindow,
  ];

  final List<_PatchResult> results = <_PatchResult>[];
  for (final _PatchResult Function(Directory, bool) patcher in patchers) {
    try {
      results.add(patcher(projectRoot, dryRun));
    } catch (error, stackTrace) {
      results.add(_PatchResult('Unknown', '-', _Status.error, '$error'));
      stderr.writeln(stackTrace);
    }
  }

  _printReport(results, dryRun: dryRun);

  final bool needsAttention = results.any(
    (_PatchResult r) => r.status == _Status.unrecognized || r.status == _Status.error,
  );
  exitCode = needsAttention ? 1 : 0;
}

void _printReport(List<_PatchResult> results, {required bool dryRun}) {
  stdout.writeln(
    dryRun
        ? 'persistent_window_manager — preview (--dry-run): no files will be modified\n'
        : 'persistent_window_manager — native runner patch for "hidden at launch"\n',
  );

  for (final _PatchResult r in results) {
    stdout.writeln('${_icon(r.status)} ${r.platform}');
    stdout.writeln('   ${r.path}');
    stdout.writeln('   ${r.message}');
    stdout.writeln();
  }

  final int toFix = results
      .where(
        (_PatchResult r) => r.status == _Status.unrecognized || r.status == _Status.error,
      )
      .length;

  if (toFix == 0) {
    stdout.writeln(
      dryRun
          ? 'No issues found. Run without --dry-run to apply the changes.'
          : 'Done. Restart the app to see the effect. Review "git diff" before committing.',
    );
  } else {
    stdout.writeln(
      '$toFix file(s) require manual changes — see the "Manual setup" section in the persistent_window_manager README.',
    );
  }
}

String _icon(_Status status) {
  switch (status) {
    case _Status.patched:
      return '✔';
    case _Status.alreadyOk:
      return '•';
    case _Status.platformNotFound:
      return '·';
    case _Status.unrecognized:
      return '⚠';
    case _Status.error:
      return '✖';
  }
}

int _countOccurrences(String haystack, String needle) {
  if (needle.isEmpty) return 0;
  int count = 0;
  int index = 0;
  while (true) {
    final int found = haystack.indexOf(needle, index);
    if (found == -1) break;
    count++;
    index = found + needle.length;
  }
  return count;
}

// ---------------------------------------------------------------------------
// Windows — windows/runner/win32_window.cpp
//
// The legacy template creates the window with WS_OVERLAPPEDWINDOW | WS_VISIBLE,
// making it immediately visible at creation — well before Dart code can apply
// the saved position, size, and maximized state. Newer templates no longer
// include WS_VISIBLE: nothing to do in that case.
// ---------------------------------------------------------------------------
_PatchResult _patchWin32Window(Directory root, bool dryRun) {
  const String platform = 'Windows — win32_window.cpp';
  final File file = File('${root.path}/windows/runner/win32_window.cpp');

  if (!file.existsSync()) {
    return _PatchResult(
      platform,
      file.path,
      _Status.platformNotFound,
      'No Windows target found in this project: nothing to do.',
    );
  }

  final String content = file.readAsStringSync();

  if (content.contains(_marker)) {
    return _PatchResult(platform, file.path, _Status.alreadyOk, 'Already patched.');
  }

  const String needle = 'WS_OVERLAPPEDWINDOW | WS_VISIBLE';

  if (!content.contains(needle)) {
    return _PatchResult(
      platform,
      file.path,
      _Status.alreadyOk,
      'WS_VISIBLE not present in CreateWindow: no change needed (template already compliant).',
    );
  }

  final int occurrences = _countOccurrences(content, needle);
  if (occurrences != 1) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      'Found $occurrences occurrences of "$needle" (expected exactly 1): manual fix required to avoid ambiguity.',
    );
  }

  if (dryRun) {
    return _PatchResult(
      platform,
      file.path,
      _Status.patched,
      '[dry-run] Would remove "| WS_VISIBLE" from CreateWindow.',
    );
  }

  final String patched = content.replaceFirst(
    needle,
    'WS_OVERLAPPEDWINDOW /* WS_VISIBLE removed by $_marker: window shown by window_manager, not at creation */',
  );
  file.writeAsStringSync(patched);

  return _PatchResult(
    platform,
    file.path,
    _Status.patched,
    'Removed "| WS_VISIBLE" from CreateWindow.',
  );
}

// ---------------------------------------------------------------------------
// Windows — windows/runner/flutter_window.cpp
//
// Since Flutter 3.7, the template registers a SetNextFrameCallback that calls
// this->Show() as soon as Flutter renders its first frame — again independently
// of window_manager. Only that call needs to be disabled; the rest (including
// any subsequent ForceRedraw(), which serves a different purpose) must be left
// untouched.
// ---------------------------------------------------------------------------
_PatchResult _patchFlutterWindow(Directory root, bool dryRun) {
  const String platform = 'Windows — flutter_window.cpp';
  final File file = File('${root.path}/windows/runner/flutter_window.cpp');

  if (!file.existsSync()) {
    return _PatchResult(
      platform,
      file.path,
      _Status.platformNotFound,
      'No Windows target found in this project: nothing to do.',
    );
  }

  final List<String> lines = file.readAsLinesSync();

  if (lines.any((String l) => l.contains(_marker))) {
    return _PatchResult(platform, file.path, _Status.alreadyOk, 'Already patched.');
  }

  final List<int> candidates = <int>[];
  for (int i = 0; i < lines.length; i++) {
    if (lines[i].trim() == 'this->Show();') {
      final int contextStart = i - 3 < 0 ? 0 : i - 3;
      final String context = lines.sublist(contextStart, i).join('\n');
      if (context.contains('SetNextFrameCallback')) {
        candidates.add(i);
      }
    }
  }

  if (candidates.isEmpty) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      '"this->Show();" call inside SetNextFrameCallback not found: manual fix required.',
    );
  }

  if (candidates.length > 1) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      'Found ${candidates.length} occurrences (expected exactly 1): manual fix required to avoid ambiguity.',
    );
  }

  if (dryRun) {
    return _PatchResult(
      platform,
      file.path,
      _Status.patched,
      '[dry-run] Would disable the automatic this->Show() call.',
    );
  }

  final int idx = candidates.single;
  final String indent = lines[idx].substring(0, lines[idx].indexOf('this->Show()'));
  lines[idx] = '$indent// this->Show(); // removed by $_marker: window shown by window_manager';
  file.writeAsStringSync('${lines.join('\n')}\n');

  return _PatchResult(
    platform,
    file.path,
    _Status.patched,
    'Disabled the automatic show call inside SetNextFrameCallback.',
  );
}

// ---------------------------------------------------------------------------
// Linux — linux/my_application.cc
//
// Two known template variants, both of which show the window regardless of
// window_manager:
//  - modern: gtk_widget_show hooked to the FlView "first-frame" signal
//    (first_frame_cb function);
//  - legacy: gtk_widget_show(GTK_WIDGET(window)) called immediately after
//    gtk_window_set_default_size, replaced with gtk_widget_realize
//    (still required to start rendering).
// ---------------------------------------------------------------------------
_PatchResult _patchLinuxMyApplication(Directory root, bool dryRun) {
  const String platform = 'Linux — my_application.cc';
  final File file = File('${root.path}/linux/my_application.cc');

  if (!file.existsSync()) {
    return _PatchResult(
      platform,
      file.path,
      _Status.platformNotFound,
      'No Linux target found in this project: nothing to do.',
    );
  }

  final List<String> lines = file.readAsLinesSync();

  if (lines.any((String l) => l.contains(_marker))) {
    return _PatchResult(platform, file.path, _Status.alreadyOk, 'Already patched.');
  }

  const String modernNeedle = 'gtk_widget_show(gtk_widget_get_toplevel(GTK_WIDGET(view)));';
  final List<int> modernMatches = <int>[
    for (int i = 0; i < lines.length; i++)
      if (lines[i].trim() == modernNeedle) i,
  ];

  if (modernMatches.length == 1) {
    if (dryRun) {
      return _PatchResult(
        platform,
        file.path,
        _Status.patched,
        '[dry-run] Would disable the show call in first_frame_cb (modern template variant).',
      );
    }
    final int idx = modernMatches.single;
    final String indent = lines[idx].substring(0, lines[idx].indexOf('gtk_widget_show'));
    lines[idx] = '$indent// $modernNeedle // removed by $_marker: window shown by window_manager';
    file.writeAsStringSync('${lines.join('\n')}\n');
    return _PatchResult(
      platform,
      file.path,
      _Status.patched,
      'Disabled the show call in first_frame_cb (modern template variant).',
    );
  }
  if (modernMatches.length > 1) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      'Found ${modernMatches.length} occurrences of the modern pattern (expected exactly 1): manual fix required.',
    );
  }

  const String legacyNeedle = 'gtk_widget_show(GTK_WIDGET(window));';
  final List<int> legacyMatches = <int>[];
  for (int i = 0; i < lines.length; i++) {
    if (lines[i].trim() == legacyNeedle) {
      final int contextStart = i - 5 < 0 ? 0 : i - 5;
      final bool hasSetDefaultSize =
          lines.sublist(contextStart, i).any((String l) => l.contains('gtk_window_set_default_size'));
      if (hasSetDefaultSize) {
        legacyMatches.add(i);
      }
    }
  }

  if (legacyMatches.length == 1) {
    if (dryRun) {
      return _PatchResult(
        platform,
        file.path,
        _Status.patched,
        '[dry-run] Would replace the immediate show call with gtk_widget_realize (legacy template variant).',
      );
    }
    final int idx = legacyMatches.single;
    final String indent = lines[idx].substring(0, lines[idx].indexOf('gtk_widget_show'));
    lines[idx] = '${indent}gtk_widget_realize(GTK_WIDGET(window)); '
        '// replaced by $_marker: window shown by window_manager';
    file.writeAsStringSync('${lines.join('\n')}\n');
    return _PatchResult(
      platform,
      file.path,
      _Status.patched,
      'Replaced the immediate show call with gtk_widget_realize (legacy template variant).',
    );
  }
  if (legacyMatches.length > 1) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      'Found ${legacyMatches.length} occurrences of the legacy pattern (expected exactly 1): manual fix required.',
    );
  }

  return _PatchResult(
    platform,
    file.path,
    _Status.unrecognized,
    'None of the known patterns found: manual fix required.',
  );
}

// ---------------------------------------------------------------------------
// macOS — macos/Runner/MainFlutterWindow.swift
//
// Adds `import window_manager` (if absent) and an override of
// `order(_:relativeTo:)` that calls `hiddenWindowAtLaunch()` — a function
// exposed by window_manager itself, internally idempotent, that hides the
// window on AppKit's very first ordering attempt and becomes a no-op for all
// subsequent calls (including the `windowManager.show()` that arrives later).
// ---------------------------------------------------------------------------
_PatchResult _patchMacosMainFlutterWindow(Directory root, bool dryRun) {
  const String platform = 'macOS — MainFlutterWindow.swift';
  final File file = File('${root.path}/macos/Runner/MainFlutterWindow.swift');

  if (!file.existsSync()) {
    return _PatchResult(
      platform,
      file.path,
      _Status.platformNotFound,
      'No macOS target found in this project: nothing to do.',
    );
  }

  String content = file.readAsStringSync();

  if (content.contains(_marker) || content.contains('hiddenWindowAtLaunch()')) {
    return _PatchResult(platform, file.path, _Status.alreadyOk, 'Already patched.');
  }

  if (!content.contains('class MainFlutterWindow')) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      'MainFlutterWindow class not found: manual fix required.',
    );
  }

  const String importNeedle = 'import FlutterMacOS';
  final bool needsImport = !content.contains('import window_manager');
  if (needsImport && _countOccurrences(content, importNeedle) != 1) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      '"$importNeedle" not found exactly once: manually add "import window_manager".',
    );
  }

  if (dryRun) {
    return _PatchResult(
      platform,
      file.path,
      _Status.patched,
      '[dry-run] Would add "import window_manager" (if missing) and the order(_:relativeTo:) override.',
    );
  }

  if (needsImport) {
    content = content.replaceFirst(
      importNeedle,
      '$importNeedle\nimport window_manager',
    );
  }

  final List<String> lines = content.split('\n');
  int lastBraceIdx = -1;
  for (int i = lines.length - 1; i >= 0; i--) {
    if (lines[i].trim() == '}') {
      lastBraceIdx = i;
      break;
    }
  }

  if (lastBraceIdx == -1) {
    return _PatchResult(
      platform,
      file.path,
      _Status.unrecognized,
      'Unable to locate the class closing brace: manual fix required.',
    );
  }

  final List<String> orderOverride = <String>[
    '',
    '    // Added by $_marker: window stays hidden at launch until windowManager.show() is called explicitly.',
    '    override public func order(_ place: NSWindow.OrderingMode, relativeTo otherWin: Int) {',
    '        super.order(place, relativeTo: otherWin)',
    '        hiddenWindowAtLaunch()',
    '    }',
  ];
  lines.insertAll(lastBraceIdx, orderOverride);

  file.writeAsStringSync('${lines.join('\n')}\n');

  return _PatchResult(
    platform,
    file.path,
    _Status.patched,
    needsImport
        ? 'Added "import window_manager" and the order(_:relativeTo:) override.'
        : 'Added the order(_:relativeTo:) override.',
  );
}
